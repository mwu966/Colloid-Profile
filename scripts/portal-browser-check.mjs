import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
const { chromium, firefox } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const contentSource = await readFile('src/data/homeContent.js', 'utf8')
const content = await import(`data:text/javascript;base64,${Buffer.from(contentSource).toString('base64')}`)
const base = process.env.PORTAL_URL || 'http://localhost:8000/'
const output = process.env.PORTAL_SCREENSHOTS || '/tmp/colloid-portal-check'
await mkdir(output, { recursive: true })
const failures = []
const engines = process.env.PORTAL_BROWSERS === 'all' ? ['chromium', 'firefox'] : ['firefox']
for (const engine of engines) {
  const options = { headless: true }
  if (engine === 'chromium' && process.env.CHROMIUM_EXECUTABLE) { options.executablePath = process.env.CHROMIUM_EXECUTABLE; options.args = ['--no-sandbox'] }
  const browser = await ({ chromium, firefox })[engine].launch(options)
  try {
    for (const viewport of JSON.parse(process.env.PORTAL_VIEWPORTS || '[{"width":1440,"height":900},{"width":390,"height":844},{"width":320,"height":740},{"width":768,"height":1024},{"width":1024,"height":768}]')) {
      const page = await browser.newPage({ viewport })
      const errors = []
      page.on('pageerror', e => errors.push(e.message))
      const response = await page.goto(base, { waitUntil: 'networkidle' })
      assert.equal(response.status(), 200)
      await page.evaluate(() => document.fonts.ready)
      await page.screenshot({ path: `${output}/${engine}-${viewport.width}-top.png` })
      assert.equal(await page.locator('.logo-glyph').count(), 7)
      await page.waitForFunction(() => [...document.querySelectorAll('.scene-data-block i')].some(el => getComputedStyle(el).animationName === 'data-block-glint'))
      assert.equal(await page.locator('.slide-position').count(), 0)
      assert.equal(await page.getByRole('tab', { name: '01 Profile／自己紹介', includeHidden: true }).count(), 1)
      assert.equal(await page.locator('.top-screen').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(16, 42, 67)')
      await page.evaluate(() => window.scrollTo({ top: document.querySelector('.opening-stage').offsetHeight * .3, behavior: 'instant' }))
      await page.waitForTimeout(100)
      const motion = await page.locator('.logo-glyph').evaluateAll(nodes => nodes.map(n => new DOMMatrix(getComputedStyle(n).transform).m42))
      assert(motion.every((y,i) => i % 2 ? y > 0 : y < 0))
      await page.evaluate(() => document.getElementById('intro').scrollIntoView({ behavior: 'instant' }))
      await page.waitForTimeout(300)
      assert.equal(await page.locator('[data-scene="intro"]').evaluate(el => el.inert), false)
      assert.equal(await page.locator('.top-screen').evaluate(el => el.inert), true)
      const profileFontSize = await page.locator('.slide-current .intro-category').evaluate(el => getComputedStyle(el).fontSize)
      await page.screenshot({ path: `${output}/${engine}-${viewport.width}-intro.png` })
      const introBackground = await page.locator('.scene-ivory').boundingBox()
      await page.evaluate(() => document.activeElement?.blur())
      await page.keyboard.press('ArrowDown')
      await page.waitForTimeout(850)
      assert.equal(await page.locator('.scene-layer[data-scene=links]').getAttribute('aria-hidden'), 'false')
      assert.deepEqual(await page.locator('.scene-ivory').boundingBox(), introBackground)
      await page.evaluate(() => document.activeElement?.blur())
      await page.keyboard.press('ArrowUp')
      await page.waitForTimeout(850)
      assert.equal(await page.locator('.scene-layer[data-scene=intro]').getAttribute('aria-hidden'), 'false')
      await page.locator('.opening-stage > .site-header .site-brand').hover()
      await page.mouse.wheel(0, 100)
      await page.waitForTimeout(850)
      assert.equal(await page.locator('.scene-layer[data-scene=links]').getAttribute('aria-hidden'), 'false')
      await page.evaluate(() => document.activeElement?.blur())
      await page.keyboard.press('ArrowUp')
      await page.waitForTimeout(850)
      await page.getByRole('button', { name: '次の紹介', exact: true }).click()
      await page.waitForTimeout(250)
      assert.equal(await page.locator('.slide-current .intro-category').innerText(), 'Creative')
      await page.getByRole('button', { name: '次の紹介', exact: true }).press('ArrowRight')
      assert.equal(await page.locator('.slide-current .intro-category').innerText(), 'Engineering')
      assert.equal(await page.locator('.slide-current .intro-category').evaluate(el => getComputedStyle(el).fontSize), profileFontSize)
      await page.getByRole('button', { name: '詳しく見る', exact: true }).scrollIntoViewIfNeeded()
      const scrollBefore = await page.evaluate(() => window.scrollY)
      await page.getByRole('button', { name: '詳しく見る', exact: true }).click()
      await page.waitForTimeout(600)
      const detail = page.locator('.intro-detail')
      assert(await detail.evaluate(el => el.open))
      const engineeringFontSize = await detail.locator('#detail-title').evaluate(el => getComputedStyle(el).fontSize)
      assert.equal(await page.locator('.skill-table tbody tr').count(), content.ENGINEERING_SKILL_ITEMS.length)
      for (const item of content.ENGINEERING_CAREER_SUMMARY) assert((await detail.innerText()).includes(item))
      for (const item of content.ENGINEERING_CERTIFICATIONS) assert((await detail.innerText()).includes(item))
      assert.equal(await detail.locator('.talk-list a').count(), content.ENGINEERING_TALKS.length)
      assert.equal(await detail.getByRole(viewport.width < 768 ? 'link' : 'button', { name: 'Intro に戻る', exact: true }).count(), 1)
      const skillValues = await detail.locator('.skill-rating-item').evaluateAll(nodes => nodes.map(n => ({ title: n.querySelector('h4').textContent, experience: Number(n.querySelectorAll('[role=meter]')[0].getAttribute('aria-valuenow')), specialty: Number(n.querySelectorAll('[role=meter]')[1].getAttribute('aria-valuenow')) })))
      assert.deepEqual(skillValues, content.ENGINEERING_SKILL_ITEMS)
      const segments = await detail.locator('[role=meter]').evaluateAll(nodes => nodes.map(n => ({ count: n.children.length, active: n.querySelectorAll('.is-active').length, value: Number(n.getAttribute('aria-valuenow')) })))
      assert.equal(segments.length, content.ENGINEERING_SKILL_ITEMS.length * 2)
      segments.forEach(item => { assert.equal(item.count, 5); assert.equal(item.active, item.value) })
      await detail.locator('.detail-scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
      const endGap = await detail.evaluate(el => el.querySelector('.detail-scroll').getBoundingClientRect().bottom - el.querySelector('.detail-reading').getBoundingClientRect().bottom)
      assert(endGap >= 0 && endGap <= 34, `extra bottom scroll: ${endGap}`)
      await detail.getByRole('button', { name: 'Creative', exact: true }).click()
      for (const group of content.CREATIVE_WORKS_BY_YEAR) for (const item of group.items) for (const link of item.links) assert.equal(await detail.locator(`a[href="${link.url}"]`).count(), 1)
      assert.equal(await detail.locator('.history-year').count(), content.CREATIVE_WORKS_BY_YEAR.length + 1)
      assert.equal(await detail.locator('h4#year-2016').innerText(), '2016')
      assert.equal(await detail.locator('h4#year-2014').innerText(), '2014')
      const backBefore = viewport.width < 768 ? null : await detail.locator('.detail-return-fixed').boundingBox()
      if (viewport.width < 768) assert.equal(await detail.locator('.detail-return-mobile-link').evaluate(el => getComputedStyle(el).position), 'static')
      const headerBefore = await detail.locator('.detail-sticky-heading').boundingBox()
      const categoryBefore = await detail.getByRole('navigation', { name: '詳細カテゴリ' }).boundingBox()
      await detail.locator('.detail-scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
      await page.waitForTimeout(100)
      const headerAfter = await detail.locator('.detail-sticky-heading').boundingBox()
      assert.equal(headerAfter.y, headerBefore.y, 'detail title/header must remain visible at the absolute bottom')
      assert.equal(headerAfter.y, 0)
      if (backBefore) assert.deepEqual(await detail.locator('.detail-return-fixed').boundingBox(), backBefore)
      assert.equal((await detail.getByRole('navigation', { name: '詳細カテゴリ' }).boundingBox()).y, categoryBefore.y)
      const highlight = detail.locator('.detail-menu-highlight')
      assert.notEqual(await highlight.evaluate(el => getComputedStyle(el).transitionDuration), '0s')
      const highlightBefore = await highlight.boundingBox()
      if (viewport.width >= 768) assert(await detail.evaluate(el => {
        const layout = el.querySelector('.detail-layout')
        const line = getComputedStyle(layout, '::before')
        return line.width === '1px' && Math.abs(Number.parseFloat(line.height) - layout.getBoundingClientRect().height) <= 1
      }), 'detail divider must span the full content height')
      await page.screenshot({ path: `${output}/${engine}-${viewport.width}-creative-detail.png` })
      await detail.getByRole('button', { name: 'Profile', exact: true }).click()
      await page.waitForTimeout(400)
      const highlightAfter = await highlight.boundingBox()
      assert(viewport.width < 768 ? highlightAfter.x < highlightBefore.x : highlightAfter.y < highlightBefore.y)
      assert.equal(await detail.locator('#detail-title').evaluate(el => getComputedStyle(el).fontSize), engineeringFontSize)
      for (const item of content.PROFILE_TIMELINE) assert((await detail.innerText()).includes(item))
      for (const item of content.PROFILE_HOBBIES) assert((await detail.innerText()).includes(item))
      await page.screenshot({ path: `${output}/${engine}-${viewport.width}-profile-detail.png` })
      if (viewport.width < 768) await detail.getByRole('link', { name: 'Intro に戻る', exact: true }).click()
      else await page.keyboard.press('Escape')
      await page.waitForTimeout(600)
      assert.equal(await page.locator('.intro-detail').count(), 0)
      assert.equal(await page.locator('.slide-current .intro-category').innerText(), 'Engineering')
      assert.equal(await page.locator('.slide-current .intro-category').evaluate(el => getComputedStyle(el).fontSize), profileFontSize)
      assert.equal(await page.evaluate(() => window.scrollY), scrollBefore)
      assert.equal(await page.evaluate(() => document.activeElement.textContent.trim()), '詳しく見る')
      await page.evaluate(() => document.getElementById('links').scrollIntoView({ behavior: 'instant' })); await page.waitForTimeout(120)
      const cards = content.LINK_CARD_COLUMNS.flat()
      for (const title of ['SNS', 'お絵かき系', '同人通販', '技術系']) {
        await page.getByRole('tab', { name: title, exact: true }).click()
        const urls = await page.locator('.slide-current .portal-link-row').evaluateAll(nodes => nodes.map(n => n.href))
        assert.deepEqual(urls, cards.find(c => c.title === title).links.map(l => l.url))
      }
      await page.getByRole('tab', { name: '技術系', exact: true }).press('Home')
      assert.equal(await page.getByRole('tab', { name: 'SNS', exact: true }).getAttribute('aria-selected'), 'true')
      const backgroundBefore = await page.locator('.scene-ivory').boundingBox()
      await page.screenshot({ path: `${output}/${engine}-${viewport.width}-links.png` })
      await page.evaluate(() => document.getElementById('blog').scrollIntoView({ behavior: 'instant' })); await page.waitForTimeout(120)
      assert.equal(await page.locator('.blog-posts li').count(), 4)
      const blogLink = page.locator('.blog-posts a').first()
      const textBefore = await blogLink.locator(':scope > span').boundingBox()
      const linkBounds = await blogLink.boundingBox()
      assert.equal(Math.round(textBefore.x - linkBounds.x), viewport.width < 768 ? 16 : 24)
      await blogLink.hover()
      await page.waitForTimeout(220)
      assert.equal((await blogLink.locator(':scope > span').boundingBox()).x, textBefore.x)
      assert.equal(await blogLink.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(114, 174, 201)')
      assert((await page.locator('.blog-posts li').first().innerText()).length > 10)
      await page.screenshot({ path: `${output}/${engine}-${viewport.width}-blog.png` })
      await page.evaluate(() => document.getElementById('wavebox').scrollIntoView({ behavior: 'instant' })); await page.waitForTimeout(120)
      const backgroundAfter = await page.locator('.scene-ivory').boundingBox()
      assert.deepEqual(backgroundAfter, backgroundBefore, 'background must remain fixed between sections')
      const cta = await page.locator('.wavebox-cta').boundingBox()
      await page.locator('.wavebox-cta').hover()
      await page.waitForTimeout(220)
      assert.equal(await page.locator('.wavebox-cta').evaluate(el => getComputedStyle(el).outlineStyle), 'none')
      assert.equal(await page.locator('.wavebox-cta').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(114, 174, 201)')
      assert.equal(cta.height, 68)
      assert(cta.width <= 300 && cta.width >= 240)
      assert.equal(await page.locator('.wavebox-cta').getAttribute('href'), content.WAVEBOX_URL)
      await page.screenshot({ path: `${output}/${engine}-${viewport.width}-wavebox.png` })
      const overflow = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: document.documentElement.clientWidth }))
      assert(overflow.scroll <= overflow.width, JSON.stringify(overflow))
      const badExternal = await page.locator('a[target="_blank"]').evaluateAll(nodes => nodes.filter(n => !n.rel.includes('noopener') || !n.rel.includes('noreferrer')).map(n => n.href))
      assert.deepEqual(badExternal, [])
      if (viewport.width < 768) {
        await page.evaluate(() => document.getElementById('blog').scrollIntoView({ behavior: 'instant' })); await page.waitForTimeout(120)
        await page.locator('.opening-stage > .site-header .menu-trigger').click()
        const menu = page.locator('.opening-stage > .mobile-menu')
        assert(await menu.evaluate(n => n.open))
        await menu.getByRole('link', { name: '02 Links', exact: true }).click()
        await page.waitForTimeout(1200)
        assert.equal(await menu.evaluate(n => n.open), false)
        assert.equal(await page.locator('.scene-layer[data-scene=links]').getAttribute('aria-hidden'), 'false')
        for (const [id, label] of [['blog', '03 Blog'], ['wavebox', '04 WaveBox'], ['intro', '01 Intro']]) {
          await page.locator('.opening-stage > .site-header .menu-trigger').click()
          await page.waitForTimeout(450)
          await menu.getByRole('link', { name: label, exact: true }).click()
          await page.waitForTimeout(1200)
          assert.equal(await page.locator(`.scene-layer[data-scene=${id}]`).getAttribute('aria-hidden'), 'false')
        }
      }
      assert.deepEqual(errors, [])
      console.log(`PASS ${engine} ${viewport.width}×${viewport.height}: scroll, carousel, detail/return/focus/content, links, RSS, CTA, overflow, console`)
      await page.close()
    }
    const routes = await browser.newPage()
    await routes.goto(new URL('about/', base).href, { waitUntil: 'networkidle' })
    await routes.getByRole('link', { name: '戻る', exact: true }).click()
    await routes.waitForURL(new URL('./', base).href)
    await routes.goto(new URL('404.html', base).href, { waitUntil: 'networkidle' })
    await routes.getByRole('link', { name: 'Go home', exact: true }).click()
    await routes.waitForURL(new URL('./', base).href)
    console.log(`PASS ${engine} Gatsby about/404 navigation`)
    await routes.close()
    const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
    await reduced.goto(base, { waitUntil: 'networkidle' })
    await reduced.evaluate(() => document.getElementById('intro').scrollIntoView({ behavior: 'instant' }))
    await reduced.waitForTimeout(100)
    assert.equal(await reduced.locator('.scene-data-block i').first().evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.equal(await reduced.locator('.opening-scroll').evaluate(el => el.style.getPropertyValue('--glyph-travel')), '0px')
    await reduced.getByRole('button', { name: '詳しく見る', exact: true }).click()
    await reduced.waitForTimeout(50)
    await reduced.keyboard.press('Escape')
    await reduced.waitForTimeout(50)
    assert.equal(await reduced.locator('.intro-detail').count(), 0)
    console.log(`PASS ${engine} reduced-motion`)
    await reduced.close()
  } catch (error) { console.error(engine, error); failures.push(engine) } finally { await browser.close() }
}
assert.deepEqual(failures, [])
