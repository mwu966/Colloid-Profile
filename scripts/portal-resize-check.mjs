import assert from 'node:assert/strict'
const { chromium, firefox } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.PORTAL_URL || 'http://localhost:8000/'
for (const [name, engine] of [['chromium', chromium], ['firefox', firefox]]) {
  const browser = await engine.launch({ headless: true, ...(name === 'chromium' && process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE, args: ['--no-sandbox'] } : {}) })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(base, { waitUntil: 'networkidle' })
    async function show(id) {
      await page.evaluate(id => document.getElementById(id).scrollIntoView({ behavior: 'instant' }), id)
      await page.waitForTimeout(150)
    }
    async function check(id) {
      const state = await page.locator(`[data-scene=${id}]`).evaluate(el => ({ opacity: getComputedStyle(el).opacity, hidden: el.getAttribute('aria-hidden'), inert: el.inert }))
      assert.equal(state.opacity, '1', `${id} must not be frozen mid-transition`)
      assert.equal(state.hidden, 'false')
      assert.equal(state.inert, false)
    }
    for (const id of ['intro', 'links', 'blog', 'wavebox']) {
      await page.setViewportSize({ width: 390, height: 844 })
      await show(id)
      await page.setViewportSize({ width: 1440, height: 900 })
      await page.waitForTimeout(250)
      await check(id)
      await page.setViewportSize({ width: 320, height: 740 })
      await page.waitForTimeout(250)
      await check(id)
    }
    await show('intro')
    await page.locator('.opening-stage > .site-header .menu-trigger').click()
    await page.waitForTimeout(100)
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.waitForTimeout(300)
    assert.equal(await page.locator('.opening-stage > .mobile-menu').evaluate(el => el.open), false)
    await check('intro')
    await page.keyboard.press('ArrowDown')
    await page.waitForTimeout(850)
    await check('links')
    await page.setViewportSize({ width: 390, height: 844 })
    await show('intro')
    await page.keyboard.press('ArrowDown')
    await page.waitForTimeout(100)
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.waitForTimeout(250)
    await check('links')
    await page.keyboard.press('ArrowDown')
    await page.waitForTimeout(850)
    await check('blog')
    await page.setViewportSize({ width: 390, height: 844 })
    await show('intro')
    await page.getByRole('button', { name: '詳しく見る', exact: true }).click()
    await page.waitForTimeout(600)
    assert.equal(await page.locator('.detail-return-fixed').count(), 0)
    assert.equal(await page.locator('.detail-return-mobile-link').evaluate(el => getComputedStyle(el).position), 'static')
    await page.locator('.detail-scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.waitForTimeout(200)
    assert.equal((await page.locator('.detail-return-fixed').boundingBox()).x, 48)
    await page.locator('.intro-detail').getByRole('button', { name: 'Intro に戻る', exact: true }).click()
    await page.waitForTimeout(600)
    await check('intro')
    assert.equal(await page.locator('.intro-detail').count(), 0)
    await page.getByRole('button', { name: '詳しく見る', exact: true }).click()
    await page.waitForTimeout(600)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.waitForTimeout(200)
    await page.locator('.intro-detail').getByRole('link', { name: 'Intro に戻る', exact: true }).click()
    await page.waitForTimeout(600)
    await check('intro')
    assert.deepEqual(errors, [])
    console.log(`PASS ${name}: bidirectional resize, open menu, interrupted animation, detail return, console`)
  } finally { await browser.close() }
}
