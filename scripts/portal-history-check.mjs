import assert from 'node:assert/strict'
const {chromium,firefox} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
for(const engine of [chromium,firefox]){
 const browser=await engine.launch({headless:true,...(engine===chromium && process.env.CHROMIUM_EXECUTABLE ? {executablePath:process.env.CHROMIUM_EXECUTABLE,args:['--no-sandbox']}:{})})
 const page=await browser.newPage({viewport:{width:390,height:844}})
 await page.goto(process.env.PORTAL_URL || 'http://localhost:8000/',{waitUntil:'networkidle'})
 await page.locator('.top-scroll').click();await page.waitForTimeout(850)
 await page.locator('.intro-section .next-section').click();await page.waitForTimeout(850)
 await page.locator('.links-section .next-section').click();await page.waitForTimeout(850)
 await page.setViewportSize({width:1440,height:900});await page.waitForTimeout(200)
 await page.goBack();await page.waitForTimeout(300)
 const state=await page.locator('[data-scene=links]').evaluate(el=>({hash:location.hash,opacity:getComputedStyle(el).opacity,y:scrollY,stage:document.querySelector('.opening-stage').offsetHeight}))
 assert.equal(state.hash,'#links');assert.equal(state.opacity,'1');assert.equal(state.y,1800)
 assert.equal(await page.evaluate(()=>document.activeElement.id),'links-heading')
 await page.goForward();await page.waitForTimeout(300)
 assert.equal(await page.locator('[data-scene=blog]').evaluate(el=>getComputedStyle(el).opacity),'1')
 await page.goBack();await page.waitForTimeout(200);await page.goBack();await page.waitForTimeout(200)
 assert.equal(await page.evaluate(()=>location.hash),'#intro')
 await page.getByRole('button',{name:'詳しく見る',exact:true}).click();await page.waitForTimeout(600)
 await page.goBack();await page.waitForTimeout(1500)
 assert.equal(await page.locator('.intro-detail').count(),0)
 assert.equal(await page.evaluate(()=>scrollY),0)
 await page.goForward();await page.waitForTimeout(300)
 assert.equal(await page.locator('[data-scene=intro]').evaluate(el=>getComputedStyle(el).opacity),'1')
 console.log('PASS',engine.name(),'back/forward after resize, focus, open detail, forward restoration')
 await browser.close()
}
